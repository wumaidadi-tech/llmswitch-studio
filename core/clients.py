# -*- coding: utf-8 -*-
"""把当前 llama-server 的接入信息写进客户端配置。

只有"格式已知、写入是安全合并"的目标才会直接改文件：
  · WorkBuddy  ~/.workbuddy/models.json   —— JSON 数组，按 id 合并，未知字段原样保留
  · 通用 .env / client.json  —— 写在数据目录里，任何 agent / 脚本都能用

其它客户端（Codex CLI、Cursor…）的配置结构各异、还可能被别的工具托管
（本机 Codex 就由 cc-switch 代管），所以只提供"复制片段"，不擅自改。
所有写入都先备份，原子替换。
"""
import json
import os
import time

from . import paths


def _home(*parts):
    return os.path.join(os.path.expanduser("~"), *parts)


def _backup(path):
    """写之前留一份带时间戳的备份；返回备份路径（没有原文件时返回空）。"""
    if not os.path.isfile(path):
        return ""
    bak = "%s.bak-%s" % (path, time.strftime("%Y%m%d-%H%M%S"))
    try:
        with open(path, "rb") as src, open(bak, "wb") as dst:
            dst.write(src.read())
        return bak
    except Exception:
        return ""


def _atomic_write(path, text):
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    os.replace(tmp, path)


def targets():
    wb = _home(".workbuddy", "models.json")
    codex = _home(".codex", "config.toml")
    return [
        {"id": "workbuddy", "name": "WorkBuddy", "path": wb, "kind": "models.json",
         "installed": os.path.isfile(wb), "writable": True,
         "note": "按模型 id 合并；不认识的字段原样保留"},
        {"id": "codex", "name": "Codex CLI", "path": codex, "kind": "toml",
         "installed": os.path.isfile(codex), "writable": False,
         "note": "配置可能由 cc-switch 托管，只导出片段、不直接改"},
        {"id": "env", "name": "通用 .env", "path": os.path.join(paths.WORK_DIR, "client.env"),
         "kind": "env", "installed": True, "writable": True,
         "note": "OPENAI_BASE_URL / OPENAI_API_KEY / OPENAI_MODEL，脚本可直接读"},
        {"id": "json", "name": "通用 client.json", "path": os.path.join(paths.WORK_DIR, "client.json"),
         "kind": "json", "installed": True, "writable": True,
         "note": "给读 JSON 的 agent / 自写脚本用"},
    ]


def _entry(model, base_url, api_key, max_ctx, images):
    return {
        "id": model,
        "name": model,
        "vendor": "Custom",
        "url": base_url.rstrip("/") + "/chat/completions",
        "apiKey": api_key,
        "supportsToolCall": True,
        "supportsImages": bool(images),
        "supportsReasoning": True,
        "useCustomProtocol": True,
        "maxInputTokens": int(max_ctx or 131072),
    }


def write_workbuddy(model, base_url, api_key, max_ctx, images):
    path = _home(".workbuddy", "models.json")
    data = []
    if os.path.isfile(path):
        try:
            with open(path, encoding="utf-8") as f:
                data = json.load(f)
        except Exception as exc:                    # noqa: BLE001
            return False, "读不懂现有 models.json：%s" % exc, path, ""
        if not isinstance(data, list):
            return False, "现有 models.json 不是数组，未改动", path, ""
    want = _entry(model, base_url, api_key, max_ctx, images)
    hit = None
    for it in data:
        if isinstance(it, dict) and (it.get("id") == model or it.get("name") == model):
            hit = it
            break
    if hit is None:
        data.append(want)
    else:
        hit.update(want)          # 合并：未知字段保留
    bak = _backup(path)
    _atomic_write(path, json.dumps(data, ensure_ascii=False, indent=2) + "\n")
    return True, ("已更新" if bak else "已新增") + "「%s」" % model, path, bak


def write_env(model, base_url, api_key, max_ctx, images):
    path = os.path.join(paths.WORK_DIR, "client.env")
    root = base_url.rstrip("/")
    text = "\n".join([
        "# generated by LLMSwitch Studio %s" % time.strftime("%Y-%m-%d %H:%M:%S"),
        "# 任意 agent / 脚本都可以读这三个变量",
        "OPENAI_BASE_URL=%s" % root,
        "OPENAI_API_KEY=%s" % api_key,
        "OPENAI_MODEL=%s" % model,
        "",
        "# 别名（不同工具认的变量名不一样）",
        "OPENAI_API_BASE=%s" % root,
        "LLM_BASE_URL=%s" % root,
        "LLM_MODEL=%s" % model,
        "",
    ])
    bak = _backup(path)
    _atomic_write(path, text)
    return True, "已写入 %s" % os.path.basename(path), path, bak


def write_json(model, base_url, api_key, max_ctx, images):
    path = os.path.join(paths.WORK_DIR, "client.json")
    obj = {
        "base_url": base_url.rstrip("/"),
        "api_key": api_key,
        "model": model,
        "max_input_tokens": int(max_ctx or 131072),
        "supports_images": bool(images),
        "updated_at": time.strftime("%Y-%m-%d %H:%M:%S"),
    }
    bak = _backup(path)
    _atomic_write(path, json.dumps(obj, ensure_ascii=False, indent=2) + "\n")
    return True, "已写入 %s" % os.path.basename(path), path, bak


def write(target, model, base_url, api_key, max_ctx, images):
    fn = {"workbuddy": write_workbuddy, "env": write_env, "json": write_json}.get(target)
    if fn is None:
        return False, "不支持直接写入该客户端（可复制片段或用 .env / client.json）", "", ""
    return fn(model, base_url, api_key, max_ctx, images)
